#!/usr/bin/env python3
"""B1L-0324: turns the boot menu's icons (uefi/XnuLoader/icons/*.png, given by the owner) into uefi/XnuLoader/MenuIcons.h:
0xAARRGGBB pixels, not premultiplied. No PIL on the build Mac: a PNG reader for 8-bit, non-interlaced RGB/RGBA/grey.
App icons: cropped to what is not white, cut to a rounded square (the white corners of the pictures go). The reboot
arrow: black on white -> white with the darkness as alpha (white on the black screen)."""
import struct, sys, zlib, os

def read_png(path):
    d = open(path, 'rb').read()
    assert d[:8] == b'\x89PNG\r\n\x1a\n', path
    pos, idat, w, plte = 8, b'', 0, b''
    while pos < len(d):
        n, t = struct.unpack('>I4s', d[pos:pos + 8]); body = d[pos + 8:pos + 8 + n]; pos += 12 + n
        if t == b'IHDR':
            w, h, depth, ctype, _, _, inter = struct.unpack('>IIBBBBB', body)
            assert depth == 8 and inter == 0 and ctype in (0, 2, 3, 4, 6), (path, depth, ctype, inter)
        elif t == b'PLTE':
            plte = body
        elif t == b'IDAT':
            idat += body
    ch = {0: 1, 2: 3, 3: 1, 4: 2, 6: 4}[ctype]
    raw, stride, prev, rows = zlib.decompress(idat), w * ch, bytearray(w * ch), []
    for y in range(h):
        f = raw[y * (stride + 1)]; line = bytearray(raw[y * (stride + 1) + 1:(y + 1) * (stride + 1)])
        for i in range(stride):
            a = line[i - ch] if i >= ch else 0; b = prev[i]; c = prev[i - ch] if i >= ch else 0
            if f == 1: line[i] = (line[i] + a) & 255
            elif f == 2: line[i] = (line[i] + b) & 255
            elif f == 3: line[i] = (line[i] + (a + b) // 2) & 255
            elif f == 4:
                p = a + b - c; pa, pb, pc = abs(p - a), abs(p - b), abs(p - c)
                line[i] = (line[i] + (a if pa <= pb and pa <= pc else b if pb <= pc else c)) & 255
        rows.append(line); prev = line
    def px(x, y):
        r = rows[y]; i = x * ch
        if ctype == 3: return tuple(plte[3 * r[i]:3 * r[i] + 3]) + (255,)
        if ch == 1: return (r[i], r[i], r[i], 255)
        if ch == 2: return (r[i], r[i], r[i], r[i + 1])
        if ch == 3: return (r[i], r[i + 1], r[i + 2], 255)
        return tuple(r[i:i + 4])
    return w, h, px

def sample(px, w, h, x0, y0, size, n, out):
    """Box-filters the square (x0, y0, size) of the source to n x n, 4x4 samples a pixel (bilinear-free, enough here)."""
    res = []
    for ty in range(n):
        for tx in range(n):
            acc = [0, 0, 0, 0]
            for sy in range(4):
                for sx in range(4):
                    x = min(w - 1, max(0, int(x0 + (tx + (sx + .5) / 4) * size / n)))
                    y = min(h - 1, max(0, int(y0 + (ty + (sy + .5) / 4) * size / n)))
                    p = px(x, y)
                    for k in range(4): acc[k] += p[k]
            res.append([v / 16 for v in acc])
    return res

def app_icon(path, n):
    w, h, px = read_png(path)
    xs, ys = [], []
    for y in range(0, h, 1):
        for x in range(0, w, 1):
            r, g, b, a = px(x, y)
            if a > 128 and min(r, g, b) < 235: xs.append(x); ys.append(y)
    x0, x1, y0, y1 = min(xs), max(xs), min(ys), max(ys)
    size = max(x1 - x0, y1 - y0) + 1
    cx, cy = (x0 + x1) / 2, (y0 + y1) / 2
    pix = sample(px, w, h, cx - size / 2, cy - size / 2, size, n, None)
    inset, r = n * 0.012, n * 0.225                       # a hair inside, to leave the white fringe out
    out = []
    for i, (R, G, B, A) in enumerate(pix):
        x, y = i % n, i // n
        cover = 0
        for sy in range(4):
            for sx in range(4):
                fx, fy = x + (sx + .5) / 4, y + (sy + .5) / 4
                lo, hi = inset + r, n - inset - r
                dx = lo - fx if fx < lo else fx - hi if fx > hi else 0
                dy = lo - fy if fy < lo else fy - hi if fy > hi else 0
                inside = inset <= fx <= n - inset and inset <= fy <= n - inset and dx * dx + dy * dy <= r * r
                cover += inside
        a = int(A * cover / 16 + .5)
        out.append(a << 24 | int(R + .5) << 16 | int(G + .5) << 8 | int(B + .5))
    return out

def glyph(path, n):
    w, h, px = read_png(path)
    pix = sample(px, w, h, 0, 0, min(w, h), n, None)
    return [int(255 - (R + G + B) / 3 + .5) << 24 | 0xffffff for R, G, B, A in pix]   # inverted: white on black

def emit(f, name, n, pix):
    f.write('#define %s_SIZE %du\nstatic const uint32_t %s[%d * %d] = {\n' % (name.upper(), n, name, n, n))
    for i in range(0, len(pix), 8):
        f.write('    ' + ', '.join('0x%08xu' % p for p in pix[i:i + 8]) + ',\n')
    f.write('};\n\n')

if __name__ == '__main__':
    d = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'uefi', 'XnuLoader')
    with open(os.path.join(d, 'MenuIcons.h'), 'w') as f:
        f.write('/* Generated by scripts/make-menu-icons.py from the PNG files of uefi/XnuLoader/icons (B1L-0324); do not edit.\n'
                ' * The pictures were given by the owner for this boot menu. 0xAARRGGBB, not premultiplied. */\n'
                '#ifndef B2L_MENU_ICONS_H\n#define B2L_MENU_ICONS_H\n#include <stdint.h>\n\n')
        emit(f, 'icon_ios26_big', 240, app_icon(os.path.join(d, 'icons', 'ios26.png'), 240))
        emit(f, 'icon_ios26', 128, app_icon(os.path.join(d, 'icons', 'ios26.png'), 128))
        emit(f, 'icon_settings', 128, app_icon(os.path.join(d, 'icons', 'settings.png'), 128))
        emit(f, 'icon_reboot', 128, glyph(os.path.join(d, 'icons', 'reboot.png'), 128))
        f.write('#endif\n')
    print('MenuIcons.h written')
